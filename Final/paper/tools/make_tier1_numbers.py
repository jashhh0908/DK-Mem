"""Tier-1 numbers for the paper (configs A-D, 3B backbone, seed 0), from the key-holder scoring of the stored run. No inference.

    python paper/tools/make_tier1_numbers.py           # writes paper/generated/{tier1_numbers.tex, tier1_table.tex, tier1_numbers.json}
    python paper/tools/make_tier1_numbers.py --check   # exit 1 if those files are stale

Inputs (gitignored; held by the key holder) were produced by the pre-registered commands in
results/full_ad_3b_s0_20261010/KEY_HOLDER_COMMANDS.md (score, ablation) and are pinned by sha256 below.

Two views, both reported:
* IN-SCOPE HINDI: kinship + honorific_register + name_variant on Hindi = the 36 gold-different / 27 gold-same source pairs that Tier 2 was
  built from (summed from the score's "distinction_class x language" cells; asserted).
* ALL 173 pairs (hi, ko, tr, de; includes out-of-scope classes the lexicon does not cover). Labelled "Tier 1 v2, LLM-annotated, provisional".
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SCORED = REPO / "results" / "full_ad_3b_s0_20261010_scored"
PINS = {"score.json": "b362c5e3471ee301994541485f98fa4932cc2ab618e82a2431c3f8bf70cb40be",
        "ablation.json": "3ea00757d643d19e383643a5cd1fa3115edaef54932151bf749a226d629bcea0"}
OUT = REPO / "paper" / "generated"
IN_SCOPE = ("kinship", "honorific_register", "name_variant")
MODES = {"off": "Off", "lexicon": "Lex", "lexicon+llm": "Llm"}
MODE_LABEL = {"off": "gate off", "lexicon": "gate on", "lexicon+llm": "gate on + LLM fallback"}

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_numbers import wilson  # noqa: E402  (same interval method as the Tier-2 numbers)


def group_tag(g) -> str:
    if g["label"] != "D":
        return g["label"]
    return "D" + {0.8: "Eighty", 0.85: "EightyFive", 0.9: "Ninety"}[round(g["tau"], 2)]


def in_scope_hindi(mode: dict) -> dict:
    cells = mode["breakdown"]["distinction_class x language"]
    fm = sum(cells[f"{c} x hi"]["false_merged"] for c in IN_SCOPE)
    nd = sum(cells[f"{c} x hi"]["n_different"] for c in IN_SCOPE)
    mi = sum(cells[f"{c} x hi"]["missed"] for c in IN_SCOPE)
    ns = sum(cells[f"{c} x hi"]["n_same"] for c in IN_SCOPE)
    assert (nd, ns) == (36, 27), (nd, ns)        # the same 63 source pairs as Tier 2
    return {"FCR": {"k": fm, "n": nd, "ci95": wilson(fm, nd)}, "MCR": {"k": mi, "n": ns, "ci95": wilson(mi, ns)}}


def overall(mode: dict) -> dict:
    o = mode["overall"]
    return {"FCR": {"k": o["false_merged"], "n": o["n_different"], "ci95": tuple(o["fcr_ci95"])},
            "MCR": {"k": o["missed"], "n": o["n_same"], "ci95": tuple(o["mcr_ci95"])}}


def build(score: dict, ablation: dict) -> dict:
    out = {"source": {n: PINS[n] for n in PINS}, "groups": {}}
    abl = {a["group_id"]: a for a in ablation["ablations"]}
    for g in score["groups"]:
        tag = group_tag(g)
        entry = {"group_id": g["group_id"], "config": g["label"], "tau": g["tau"], "modes": {}}
        for mode, m in g["modes"].items():
            e = {"in_scope_hindi": in_scope_hindi(m), "all": overall(m)}
            a = abl[g["group_id"]]["modes"].get(mode, {})
            if "paired_vs_off" in a:
                e["paired_vs_off_all_pairs"] = a["paired_vs_off"]
                e["gate"] = a.get("gate")
            entry["modes"][mode] = e
        out["groups"][tag] = entry
    return out


def frac(c):
    return f"{c['k']}/{c['n']}"


def ci(c):
    return f"[{c['ci95'][0]:.2f}, {c['ci95'][1]:.2f}]"


def macros(n: dict) -> str:
    L = ["% GENERATED by paper/tools/make_tier1_numbers.py (Tier 1 v2, LLM-annotated, provisional; 3B backbone, seed 0). Do not edit.",
         "% e.g. \\TOneCOffHiFCR -> in-scope Hindi FCR of config C, gate off; \\TOneCOffAllFCR -> all 173 pairs."]
    for tag, g in n["groups"].items():
        for mode, e in g["modes"].items():
            mt = MODES[mode]
            for view, vt in (("in_scope_hindi", "Hi"), ("all", "All")):
                for m in ("FCR", "MCR"):
                    c = e[view][m]
                    base = f"TOne{tag}{mt}{vt}{m}"
                    L += [f"\\newcommand{{\\{base}}}{{{frac(c)}}}", f"\\newcommand{{\\{base}ci}}{{{ci(c)}}}"]
            if "gate" in e and e["gate"]:
                L.append(f"\\newcommand{{\\TOne{tag}{mt}Vetoes}}{{{e['gate'].get('vetoed_to_keep_both', 0)}}}")
    return "\n".join(L) + "\n"


def table(n: dict) -> str:
    L = ["% GENERATED by paper/tools/make_tier1_numbers.py. Do not edit.", "\\begin{tabular}{llcccc}", "\\toprule",
         "Config & DK-Mem & FCR (in-scope hi) & MCR (in-scope hi) & FCR (all) & MCR (all) \\\\", "\\midrule"]
    for tag, g in n["groups"].items():
        name = g["config"] if g["tau"] is None else f"D ($\\tau$={g['tau']:.2f})"
        for mode, e in g["modes"].items():
            cells = [f"{frac(e[v][m])} {ci(e[v][m])}" for v in ("in_scope_hindi", "all") for m in ("FCR", "MCR")]
            L.append(f"{name} & {MODE_LABEL[mode]} & {' & '.join(cells)} \\\\")
        L.append("\\midrule")
    L[-1] = "\\bottomrule"
    L.append("\\end{tabular}")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    raw = {}
    for name, want in PINS.items():
        b = (SCORED / name).read_bytes()
        if hashlib.sha256(b).hexdigest() != want:
            raise SystemExit(f"{SCORED / name} does not match its pinned sha256: re-run the KEY_HOLDER_COMMANDS into a fresh directory and re-pin")
        raw[name] = json.loads(b)
    n = build(raw["score.json"], raw["ablation.json"])
    files = {"tier1_numbers.tex": macros(n), "tier1_table.tex": table(n), "tier1_numbers.json": json.dumps(n, indent=1, sort_keys=True) + "\n"}
    if a.check:
        stale = [f for f, t in files.items() if not (OUT / f).exists() or (OUT / f).read_text(encoding="utf-8") != t]
        print("stale:" if stale else "up to date", *stale)
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for f, t in files.items():
        (OUT / f).write_text(t, encoding="utf-8", newline="\n")
    print("wrote", *[f"paper/generated/{f}" for f in files])
    return 0


if __name__ == "__main__":
    sys.exit(main())
