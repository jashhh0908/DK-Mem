"""Config D similarity figure and its numbers, from the verified Tier-2 entity report (data only; selects NO threshold).

    python paper/tools/make_figures.py            # writes paper/figures/d_cosine.{pdf,png} and paper/generated/figure_numbers.tex
    python paper/tools/make_figures.py --check    # exit 1 if figure_numbers.tex is stale (the PDF is not byte-compared: renderers differ)

For each arm (Main = v1.0, Mirror = v1.1m) the raw bge-m3 cosine of the injected pair is drawn for gold-same and gold-different pairs. The
dashed line is the pilot value tau = 0.90 of the runs, drawn only to show where it sits; it is NOT an operating point. Medians, minima and
maxima are emitted as macros so the text never types them.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import statistics
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_numbers import ARM_TAG, REPORT, REPORT_SHA256  # noqa: E402

OUT_FIG = REPO / "paper" / "figures"
OUT_GEN = REPO / "paper" / "generated"
TAU = 0.90
REL_TAG = {"different": "Diff", "same": "Same"}


def cosines(report: dict) -> dict:
    out = {}
    for arm, a in report["arms"].items():
        run = next(v for k, v in a["runs"].items() if v["pipeline_config"] == "D" and v["dkmem_mode"] == "off")
        out[ARM_TAG[arm]] = {rel: sorted(p["similarity"] for p in run["pairs"] if p["relation"] == rel) for rel in REL_TAG}
        assert (len(out[ARM_TAG[arm]]["different"]), len(out[ARM_TAG[arm]]["same"])) == (42, 27)
        assert all(s is not None for rel in REL_TAG for s in out[ARM_TAG[arm]][rel])
    return out


def macros(c: dict) -> str:
    L = ["% GENERATED by paper/tools/make_figures.py from the verified entity report. Do not edit.",
         "% \\MainDiffMedian = median cosine of gold-different pairs in the Main arm; also Min, Max; Same; Mirror."]
    for arm, d in c.items():
        for rel, vals in d.items():
            t = REL_TAG[rel]
            L += [f"\\newcommand{{\\{arm}{t}Median}}{{{statistics.median(vals):.2f}}}", f"\\newcommand{{\\{arm}{t}Min}}{{{vals[0]:.2f}}}",
                  f"\\newcommand{{\\{arm}{t}Max}}{{{vals[-1]:.2f}}}",
                  f"\\newcommand{{\\{arm}{t}AboveTau}}{{{sum(v > TAU for v in vals)}/{len(vals)}}}"]
    return "\n".join(L) + "\n"


def draw(c: dict) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    colors = {"different": "#0072B2", "same": "#D55E00"}          # colour-blind-safe pair
    label = {"different": "gold-different (should stay apart)", "same": "gold-same (should merge)"}
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.7), sharey=True)
    bins = [0.40 + 0.025 * i for i in range(0, 25)]            # 0.40 .. 1.00: every pair is drawn (max cosine 0.96)
    assert all(0.40 <= v <= 1.0 for d in c.values() for vals in d.values() for v in vals)
    for ax, (arm, d) in zip(axes, c.items()):
        for rel in ("different", "same"):
            ax.hist(d[rel], bins=bins, alpha=0.65, color=colors[rel], label=label[rel], edgecolor="white", linewidth=0.5)
            ax.axvline(statistics.median(d[rel]), color=colors[rel], linewidth=1.4)
        ax.axvline(TAU, color="black", linestyle="--", linewidth=1)
        ax.text(TAU - 0.005, ax.get_ylim()[1] * 0.92, r"pilot $\tau$=0.90", ha="right", va="top", fontsize=7)
        ax.set_title(f"{arm} arm", fontsize=9)
        ax.set_xlabel("bge-m3 cosine of the pair", fontsize=8)
        ax.tick_params(labelsize=7)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
    axes[0].set_ylabel("pairs", fontsize=8)
    axes[0].legend(fontsize=6.5, frameon=False, loc="upper left")
    fig.tight_layout()
    OUT_FIG.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT_FIG / "d_cosine.pdf")
    fig.savefig(OUT_FIG / "d_cosine.png", dpi=200)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--report", type=Path, default=REPORT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    raw = a.report.read_bytes()
    if hashlib.sha256(raw).hexdigest() != REPORT_SHA256:
        raise SystemExit(f"{a.report} is not the verified report (sha256 mismatch)")
    c = cosines(json.loads(raw))
    text = macros(c)
    if a.check:
        p = OUT_GEN / "figure_numbers.tex"
        stale = not p.exists() or p.read_text(encoding="utf-8") != text
        print("stale: figure_numbers.tex" if stale else "up to date")
        return 1 if stale else 0
    OUT_GEN.mkdir(parents=True, exist_ok=True)
    (OUT_GEN / "figure_numbers.tex").write_text(text, encoding="utf-8", newline="\n")
    draw(c)
    print("wrote paper/figures/d_cosine.pdf, d_cosine.png and paper/generated/figure_numbers.tex")
    return 0


if __name__ == "__main__":
    sys.exit(main())
