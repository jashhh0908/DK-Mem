"""Turn the filled native-review sheets into paper macros + the exclusion list (lossless: every verdict is counted, nothing dropped).

    python paper/tools/summarize_reviews.py
      -> paper/generated/review_summary.tex   (\\ReviewHiCorrect, \\ReviewMrWrong, ... counts per sheet and verdict)
      -> paper/generated/review_summary.json
      -> paper/review/exclusions.txt          (Hindi evaluated pairs marked wrong or ambiguous; feed to make_numbers.py --exclude)

Blank verdicts are counted as "unreviewed", never as correct.
"""
from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
REVIEW = REPO / "paper" / "review"
OUT = REPO / "paper" / "generated"
SHEETS = {"hi_pairs_review.csv": "HiPairs", "mr_pairs_review.csv": "MrPairs", "gu_pairs_review.csv": "GuPairs",
          "mr_bank_review.csv": "MrBank", "gu_bank_review.csv": "GuBank", "mr_lexicon_review.csv": "MrLexicon", "gu_lexicon_review.csv": "GuLexicon"}
NORMAL = {"correct": "Correct", "ok": "Correct", "wrong": "Wrong", "ambiguous": "Ambiguous", "unsure": "Ambiguous", "": "Unreviewed"}


def verdict_col(header):
    return next(c for c in header if c.startswith("verdict"))


def main() -> int:
    summary, exclusions, lines = {}, [], ["% GENERATED by paper/tools/summarize_reviews.py from paper/review/*.csv. Do not edit."]
    for name, tag in SHEETS.items():
        p = REVIEW / name
        if not p.exists():
            continue
        with open(p, encoding="utf-8-sig", newline="") as fh:
            rows = list(csv.DictReader(fh))
        vc = verdict_col(rows[0].keys()) if rows else None
        counts = Counter(NORMAL.get((r.get(vc) or "").strip().lower(), "Other") for r in rows)
        summary[name] = {"rows": len(rows), **counts}
        lines.append(f"\\newcommand{{\\Review{tag}Total}}{{{len(rows)}}}")
        for k in ("Correct", "Wrong", "Ambiguous", "Unreviewed", "Other"):
            lines.append(f"\\newcommand{{\\Review{tag}{k}}}{{{counts.get(k, 0)}}}")
        if name == "hi_pairs_review.csv":
            exclusions += [r["injected_pair_id"] for r in rows if NORMAL.get((r.get(vc) or "").strip().lower()) in ("Wrong", "Ambiguous")]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "review_summary.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    (OUT / "review_summary.json").write_text(json.dumps(summary, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    (REVIEW / "exclusions.txt").write_text("# Hindi evaluated pairs the in-team native review marked wrong/ambiguous\n" + "".join(x + "\n" for x in exclusions),
                                           encoding="utf-8", newline="\n")
    print(json.dumps(summary, indent=1), "\nexclusions:", len(exclusions))
    return 0


if __name__ == "__main__":
    sys.exit(main())
